//helper function to daemonize the program when -d is specified
static int daemonize(void)
{
    pid_t pid = fork();
    if (pid < 0) {
        return -1;
    }
    if (pid > 0) {
        // Parent exits
        exit(0);
    }

    // Child continues in a new session
    if (setsid() < 0) {
        return -1;
    }

    // Second fork to prevent reacquiring a controlling terminal
    pid = fork();
    if (pid < 0) {
        return -1;
    }
    if (pid > 0) {
        exit(0);
    }

    umask(0);
    if (chdir("/") < 0) {
        return -1;
    }

    // Redirect stdin/stdout/stderr to /dev/null
    int fd = open("/dev/null", O_RDWR);
    if (fd < 0) {
        return -1;
    }

    (void)dup2(fd, STDIN_FILENO);
    (void)dup2(fd, STDOUT_FILENO);
    (void)dup2(fd, STDERR_FILENO);

    if (fd > STDERR_FILENO) {
        close(fd);
    }

    return 0;
}

//this function was fully generated by ChatGPT
