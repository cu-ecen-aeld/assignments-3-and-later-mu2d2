//helper function to append a packet to the output file and then send the full file to the client
static int append_packet_and_send_file(int client_fd, const char *packet, size_t packet_len, char *io_buf, size_t io_buf_len)
{
    // Append packet to file
    int output_fd = open(outputfile, O_WRONLY | O_CREAT | O_APPEND, 0644);
    if (output_fd < 0)
    {
        return -1;
    }

    if (write_all(output_fd, packet, packet_len) < 0)
    {
        close(output_fd);
        return -1;
    }
    close(output_fd);

    // Send full file back to client (streaming)
    int read_fd = open(outputfile, O_RDONLY);
    if (read_fd < 0)
    {
        return -1;
    }

    ssize_t bytes_read;
    while ((bytes_read = read(read_fd, io_buf, io_buf_len)) > 0)
    {
        if (send_all(client_fd, io_buf, (size_t)bytes_read) < 0)
        {
            close(read_fd);
            return -1;
        }
    }

    close(read_fd);

    if (bytes_read < 0)
    {
        return -1;
    }

    return 0;
}

//handles one client connection independently
//this code block is based on original per-connection logic moved from main()
//modified to operate inside a pthread and use thread_node struct for client info and logging
static void *connection_thread(void *arg)
{
    struct thread_node *node = (struct thread_node *)arg;
    int new_socket = node->client_fd;

    struct sockaddr_in address;
    socklen_t addrlen = sizeof(address);

    char buffer[BUFFER_SIZE];

    // Initialize accumulated data buffer for storing partial/complete packets
    size_t accumulated_size = 0;             // Current size of accumulated data
    size_t allocated_size = BUFFER_SIZE;     // Currently allocated memory (capacity)
    char *accumulated_data = (char *)malloc(allocated_size);

    if (accumulated_data == NULL) {
        syslog(LOG_ERR, "malloc failed for accumulated_data");
        goto thread_cleanup;
    }

    accumulated_data[0] = '\0';

    // Receive data in a loop until connection closes
    while (1)
    {
         //this code section was partially generated by ChatGPT
        //link to chat session: https://chatgpt.com/share/6990b762-3dd8-8008-b70d-03f9fc138aca
        //if signal is caught, stop receiving new data (finish current connection cleanly)
        if (exit_requested) {
            break;
        }

        // Receive chunk of data from socket
        int valread = recv(new_socket, buffer, BUFFER_SIZE, 0);

        // Handle recv errors and connection closure
        if (valread < 0)
        {
            if (errno == EINTR && exit_requested) {
                break;
            }
            syslog(LOG_ERR, "recv error from %s: %s", node->ipstr, strerror(errno));
            break;
        }

        if (valread == 0)// Connection closed by client
        {
            //this code section was fully generated by ChatGPT
            //link to chat session: https://chatgpt.com/share/6990b762-3dd8-8008-b70d-03f9fc138aca
            //flush any remaining data in accumulated buffer to file before closing connection
            //could be partial packet without newline, but we will write it anyway to avoid data loss
            if (accumulated_size > 0)
            {
                if (append_packet_and_send_file(new_socket, accumulated_data, accumulated_size, buffer, BUFFER_SIZE) < 0)
                {
                    syslog(LOG_ERR, "Failed to append/send final packet for client %s", node->ipstr);
                    goto thread_cleanup;
                }
                //reset accumulated buffer
                accumulated_size = 0;
                accumulated_data[0] = '\0';
            }
            break;
        }

        //this code section was fully generated by ChatGPT
        //link to chat session: https://chatgpt.com/share/6990b762-3dd8-8008-b70d-03f9fc138aca
        //Ensure capacity for new data plus null terminator (avoid overflow)
        size_t needed = accumulated_size + (size_t)valread + 1;
        if (needed > allocated_size)
        {
            size_t new_size = allocated_size;
            while (new_size < needed) {
                new_size *= 2;
            }

            char *temp = (char *)realloc(accumulated_data, new_size);
            if (temp == NULL)
            {
                syslog(LOG_ERR, "realloc failed, closing connection");
                goto thread_cleanup;
            }
            accumulated_data = temp;
            allocated_size = new_size;
        }

        //copy received data into accumulated buffer and update size
        memcpy(accumulated_data + accumulated_size, buffer, (size_t)valread);
        accumulated_size += (size_t)valread;

        //null terminate the buffer for string function compatibility (strchr in packet processing)
        accumulated_data[accumulated_size] = '\0';


        //this code section was partially generated by ChatGPT
        //link to chat session: https://chatgpt.com/share/6990b762-3dd8-8008-b70d-03f9fc138aca
        //Process complete packets (lines terminated by newline) using append_packet_and_send_file()
        char *packet_end;
        while ((packet_end = strchr(accumulated_data, '\n')) != NULL)
        {
            size_t packet_len = (size_t)(packet_end - accumulated_data + 1);

            if (append_packet_and_send_file(new_socket, accumulated_data, packet_len, buffer, BUFFER_SIZE) < 0)
            {
                syslog(LOG_ERR, "Failed to append/send packet for client %s", node->ipstr);
                goto thread_cleanup;
            }
            //Remove processed packet from accumulated buffer 
            accumulated_size -= packet_len;
            memmove(accumulated_data, accumulated_data + packet_len, accumulated_size);
            
            //null terminate after shifting data
            accumulated_data[accumulated_size] = '\0';
        }
    }

thread_cleanup:
    if (accumulated_data)
    {
        free(accumulated_data);
    } 

    close(new_socket);
    node->client_fd = -1;
    syslog(LOG_INFO, "Closed connection from %s", node->ipstr);

    node->completed = 1;
    return NULL;
}


