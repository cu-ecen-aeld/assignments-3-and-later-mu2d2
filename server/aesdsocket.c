//helper function to write byte by byte
static int write_all(int fd, const char *buf, size_t len)
{
    size_t off = 0;
    while (off < len) {
        ssize_t w = write(fd, buf + off, len - off);
        if (w < 0) return -1;
        off += (size_t)w;
    }
    return 0;
}

