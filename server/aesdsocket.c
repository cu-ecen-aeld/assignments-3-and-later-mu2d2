//global flag
static volatile sig_atomic_t exit_requested = 0;
static int server_fd = -1;//global listen socket fd, set to -1 when shutting down to indicate no new connections should be accepted

//string to store data received from client
const char *outputfile = "/var/tmp/aesdsocketdata";

