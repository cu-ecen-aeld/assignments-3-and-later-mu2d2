//Thread Node using queue.h
struct thread_node 
{
    pthread_t thread_id;
    int client_fd;
    volatile int completed;//1 = thread completed processing, 0 = still running
    char ipstr[INET_ADDRSTRLEN];//store client IP for logging on thread completion
    SLIST_ENTRY(thread_node) entries;
};

SLIST_HEAD(thread_list_head, thread_node);
static struct thread_list_head thread_list = SLIST_HEAD_INITIALIZER(thread_list);




